OUTPUT = ROOT / "packages" / "dialogue_engine" / "semantic_nlp" / "seed.jsonl"


def main() -> None:
    from packages.dialogue_engine.semantic_nlp.labels import ACTS

    valid = set(ACTS)
    rows = []
    for question, text, act in SEED_ROWS:
        assert act in valid, act
        rows.append({"question": question, "text": text, "act": act})
    OUTPUT.write_text(
        "\n".join(json.dumps(r, ensure_ascii=False) for r in rows) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {len(rows)} seed rows -> {OUTPUT}")


if __name__ == "__main__":
    main()

    seen: set[str] = set()
    out: list[str] = []
    for pool in all_spoken_pools():
        for line in pool:
            key = line.strip()
            if key and key not in seen:
                seen.add(key)
                out.append(key)
    if MINIMAL_FALLBACK.strip() not in seen:
        out.append(MINIMAL_FALLBACK.strip())
    return tuple(out)



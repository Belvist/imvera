def time_of_day_from_hour(hour: int) -> TimeOfDay:
    """Map clock hour (0–23) to Russian time-of-day bucket."""
    if 5 <= hour < 12:
        return TimeOfDay.MORNING
    if 12 <= hour < 17:
        return TimeOfDay.DAY
    if 17 <= hour < 23:
        return TimeOfDay.EVENING
    return TimeOfDay.NIGHT


def time_of_day_now() -> TimeOfDay:
    return time_of_day_from_hour(datetime.now().hour)


def goodbye_pool_for_band(
    band: WellnessBand,
    *,
    hour: int | None = None,
) -> Tuple[str, ...]:
    """Select goodbye pool by wellness band and optional clock hour."""
    if band == WellnessBand.CRITICAL:
        return GOODBYE_CRITICAL_POOL
    if band == WellnessBand.BAD:
        return GOODBYE_BAD_POOL
    if band == WellnessBand.MEDIUM:
        return GOODBYE_MEDIUM_POOL
    if band == WellnessBand.GOOD:
        tod = time_of_day_from_hour(hour) if hour is not None else time_of_day_now()
        return GOODBYE_GOOD_BY_TIME[tod]
    # UNKNOWN → medium-safe closing
    return GOODBYE_MEDIUM_POOL



def pick_from_pool(
    pool: Sequence[str],
    *,
    avoid: Sequence[str] = (),
    index: int = 0,
) -> str:
    """Deterministic pool pick with optional rotation index."""
    if not pool:
        return ""
    avoid_set = {a.strip().lower() for a in avoid if a}
    for offset in range(len(pool)):
        candidate = pool[(index + offset) % len(pool)]
        if candidate.strip().lower() not in avoid_set:
            return candidate
    return pool[index % len(pool)]
